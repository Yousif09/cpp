#include <iostream>


int main() {



	// for loops = a loop that will execute a portion of code a specified amount of times. 
	// 3 statements: index, condition, incrementation of the index


	for(int i=10; i >= 0; i--) {

		std::cout << i << '\n'; 

	}

	std::cout << "HAPPY NEW YEAR!!\n"; 


	return 0; 
}